    function automatic logic in_bounds;
        input logic [4:0] x;
        input logic [4:0] y;
        begin
            in_bounds = (x < 5'd28) && (y < 5'd31);
        end
    endfunction

    function automatic logic [1:0] tile_from_xy(input logic [4:0] x, input logic [4:0] y);
        if (in_bounds(x, y))
            tile_from_xy = maze[y][(6'd55 - x*2) -: 2];
        else
            tile_from_xy = WALL_TILE;
    endfunction

    always_comb begin
        tile_a = tile_from_xy(x_a, y_a);
        tile_b = tile_from_xy(x_b, y_b);

        can_move_a = (tile_a != WALL_TILE && (!(x_a == 13 && y_a == 12) && !(x_a == 14 && y_a == 12)));
        can_move_b = (tile_b != WALL_TILE && (!(x_b == 12 && (y_b >= 12 && y_b <= 16)) && !(x_b == 15 && (y_b >= 12 && y_b <= 16))));
    end
